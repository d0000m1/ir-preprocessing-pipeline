const stopWords = new Set([
  'a',
  'an',
  'and',
  'are',
  'as',
  'at',
  'be',
  'but',
  'by',
  'for',
  'from',
  'he',
  'in',
  'is',
  'it',
  'of',
  'on',
  'or',
  'that',
  'the',
  'this',
  'to',
  'was',
  'were',
  'with',
  'your',
  'me',
]);

export function removeStopWords(tokens: string[]): string[] {
  return tokens.filter((token) => !stopWords.has(token));
}

